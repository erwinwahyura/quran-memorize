export function useT(): Dict {
  return dicts[useSettings().uiLang] ?? en;
}

export function relativeDay(t: Dict, ts: number, now = Date.now()): string {
  const startOf = (x: number) => new Date(new Date(x).toDateString()).getTime();
  const days = Math.round((startOf(now) - startOf(ts)) / 86400000);
  if (days <= 0) return t.today;
  if (days === 1) return t.yesterday;
  return t.daysAgo(days);
}
